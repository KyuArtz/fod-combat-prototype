#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const input = process.argv[2] || 'reports/serpent-phantom-forensic-paired-40.json';
const output = process.argv[3] || 'reports/serpent-phantom-forensic-40.md';
const report = JSON.parse(fs.readFileSync(input, 'utf8'));
const rows = report.results;
const ids = ['verra', 'kane', 'galloz', 'claude', 'tekushiki'];
const avg = (values) => values.length ? values.reduce((a,b)=>a+b,0)/values.length : 0;
const round = (value, digits=2) => Number(value.toFixed(digits));
const countBy = (values) => Object.fromEntries(Object.entries(values.reduce((m,v)=>{m[v]=(m[v]||0)+1;return m;},{})).sort((a,b)=>b[1]-a[1]));
const battlesBySeat = Object.fromEntries(['player','opponent'].map(seat=>{
 const group=rows.filter(r=>r.serpentSeat===seat);
 return [seat,{battles:group.length,wins:group.filter(r=>r.serpentWon).length,winRate:group.filter(r=>r.serpentWon).length/group.length,averageRounds:avg(group.map(r=>r.rounds)),averageKOs:avg(group.map(r=>r.serpentKOs.length))}];
}));
const serpentKOs=rows.flatMap(r=>r.serpentKOs);
const firstKOs=rows.map(r=>({seat:r.serpentSeat,round:[...r.serpentKOs].sort((a,b)=>a.round-b.round)[0]?.round,actor:[...r.serpentKOs].sort((a,b)=>a.round-b.round)[0]?.actorId}));
const phantomTargetActions=rows.flatMap(r=>r.actions.filter(a=>a.actorFaction==='phantom'&&ids.includes(a.decision?.targetId)).map(a=>({seat:r.serpentSeat,target:a.decision.targetId,actor:a.actorId,round:a.round})))
const targetCounts=countBy(phantomTargetActions.map(a=>a.target));
const phantomKOsBySource=countBy(serpentKOs.map(k=>k.lastDamageSourceId||'unknown'));
const KOsByActor=countBy(serpentKOs.map(k=>k.actorId));
const verraActions=rows.flatMap(r=>r.verraAudit);
const treatment=verraActions.filter(a=>['treat','remedy'].includes(a.decision?.mode));
const healEvents=rows.flatMap(r=>r.healingEvents.filter(e=>e.healerTurnActor==='verra'&&e.targetId));
const healByTarget=Object.groupBy(healEvents,e=>e.targetId);
const healingStats=Object.fromEntries(Object.entries(healByTarget).map(([target,events])=>[target,{events:events.length,requested:events.reduce((s,e)=>s+Number(e.requested||0),0),healed:events.reduce((s,e)=>s+Number(e.healed||0),0),overheal:events.reduce((s,e)=>s+Number(e.overheal||0),0)}]));
const criticalOther=verraActions.filter(a=>a.criticalAllies?.some(u=>u.id!=='verra'));
const treatmentWithOtherCritical=treatment.filter(a=>a.criticalAllies?.some(u=>u.id!=='verra'));
const treatmentSelf=treatment.filter(a=>a.decision.targetId==='verra');
const allyTreatment=treatment.filter(a=>a.decision.targetId!=='verra');
const firstKOSeatActors=Object.fromEntries(['player','opponent'].map(seat=>[seat,countBy(firstKOs.filter(k=>k.seat===seat).map(k=>k.actor))]));
const firstKOSeatRounds=Object.fromEntries(['player','opponent'].map(seat=>[seat,countBy(firstKOs.filter(k=>k.seat===seat).map(k=>k.round))]));
const pairedSeedResults=Object.groupBy(rows,r=>r.seed);
const pairedOutcomeCounts={bothWin:0,playerSeatOnly:0,opponentSeatOnly:0,bothLose:0};
for(const pair of Object.values(pairedSeedResults)){
 const player=pair.find(r=>r.serpentSeat==='player')?.serpentWon||false;
 const opponent=pair.find(r=>r.serpentSeat==='opponent')?.serpentWon||false;
 if(player&&opponent)pairedOutcomeCounts.bothWin++;
 else if(player)pairedOutcomeCounts.playerSeatOnly++;
 else if(opponent)pairedOutcomeCounts.opponentSeatOnly++;
 else pairedOutcomeCounts.bothLose++;
}
const firstKOCounts=countBy(firstKOs.map(k=>k.round));
const earlyFirstKOs=firstKOs.filter(k=>k.round<=10).length;
const selfHealHPBuckets=countBy(treatmentSelf.map(a=>Math.floor(a.verraHPPercent/10)*10));
const targetPct=Object.fromEntries(Object.entries(targetCounts).map(([id,n])=>[id,round(n/phantomTargetActions.length*100,1)]));
const summary={battles:rows.length,wins:rows.filter(r=>r.serpentWon).length,losses:rows.filter(r=>!r.serpentWon).length,winRate:round(rows.filter(r=>r.serpentWon).length/rows.length*100,1),avgRounds:round(avg(rows.map(r=>r.rounds))),avgSerpentKOs:round(avg(rows.map(r=>r.serpentKOs.length))),avgPhantomKOs:round(avg(rows.map(r=>r.phantomKOs.length))),seatStats:battlesBySeat,pairedOutcomeCounts,phantomTargetActions:phantomTargetActions.length,targetCounts,targetPct,firstKOAverageRound:round(avg(firstKOs.map(k=>k.round))),firstKOCounts:firstKOCounts,firstKOsBySeatActors:firstKOSeatActors,firstKOsBySeatRounds:firstKOSeatRounds,firstKOByRound10OrEarlier:earlyFirstKOs,koCountsByActor:KOsByActor,finalBlowsBySource:phantomKOsBySource,verra:{actions:verraActions.length,modeCounts:countBy(verraActions.map(a=>a.decision.mode||a.decision.type)),treatmentActions:treatment.length,selfTreatmentActions:treatmentSelf.length,selfTreatmentPercent:round(treatmentSelf.length/treatment.length*100,1),allyTreatmentActions:allyTreatment.length,criticalOtherAllyActions:criticalOther.length,criticalOtherDuringTreatment:treatmentWithOtherCritical.length,allyTreatmentTargets:countBy(allyTreatment.map(a=>a.decision.targetId)),selfHealHPBuckets,healingByTarget:healingStats},phantomDamageIntoSerpent:report.summary.phantomDamageIntoSerpent};
const lines=[];
lines.push('# Serpent vs Phantom — Forensic Replay (40 Paired Seeds)');
lines.push('');
lines.push('**Protocol:** 40 seed pairs / 80 battles; each seed run once with Serpent in the player seat and once in the opponent seat. Combat rules and AI were not changed. Full snapshots enabled.');
lines.push('');
lines.push('## Outcome');
lines.push(`- Serpent wins: **${summary.wins}/${summary.battles} (${summary.winRate}%)**; losses ${summary.losses}.`);
lines.push(`- Average battle length: **${summary.avgRounds} rounds**.`);
lines.push(`- Average operative KOs: Serpent **${summary.avgSerpentKOs}**, Phantom **${summary.avgPhantomKOs}**.`);
lines.push(`- First Serpent KO occurred by round 10 in **${earlyFirstKOs}/80 (${round(earlyFirstKOs/rows.length*100,1)}%)** battles; average first-KO round **${summary.firstKOAverageRound}**.`);
lines.push('');
lines.push('### Seat results');
lines.push('| Seat | Battles | Wins | Win rate | Avg. rounds | Avg. Serpent KOs |');
lines.push('|---|---:|---:|---:|---:|---:|');
for(const [seat,v] of Object.entries(battlesBySeat))lines.push(`| ${seat} | ${v.battles} | ${v.wins} | ${round(v.winRate*100,1)}% | ${round(v.averageRounds)} | ${round(v.averageKOs)} |`);
lines.push('');
lines.push('### Same-seed seat pair outcomes');
lines.push(`- Both win: ${pairedOutcomeCounts.bothWin}; player-seat only: ${pairedOutcomeCounts.playerSeatOnly}; opponent-seat only: ${pairedOutcomeCounts.opponentSeatOnly}; both lose: ${pairedOutcomeCounts.bothLose}.`);
lines.push('');
lines.push('## Phantom targeting decisions');
lines.push(`Target decisions logged against Serpent operatives: **${phantomTargetActions.length}**. This is action-target selection, not only attack actions.`);
lines.push('| Target | Decisions | Share |');lines.push('|---|---:|---:|');
for(const [id,n] of Object.entries(targetCounts))lines.push(`| ${id} | ${n} | ${targetPct[id]}% |`);
lines.push('');
lines.push('## KO patterns');
lines.push('| Serpent operative | KOs |');lines.push('|---|---:|');
for(const [id,n] of Object.entries(KOsByActor))lines.push(`| ${id} | ${n} |`);
lines.push('');
lines.push('| Phantom finisher | Final blows |');lines.push('|---|---:|');
for(const [id,n] of Object.entries(phantomKOsBySource))lines.push(`| ${id} | ${n} |`);
lines.push('');
lines.push('## Verra audit');
lines.push(`- Verra decisions recorded: **${verraActions.length}**; treatments/remedies **${treatment.length}**.`);
lines.push(`- Self-target treatments: **${treatmentSelf.length}/${treatment.length} (${summary.verra.selfTreatmentPercent}%)**; ally-target treatments **${allyTreatment.length}**.`);
lines.push(`- Verra actions with a critical ally other than herself (HP ≤ 30%): **${criticalOther.length}**; treatment decisions during those states: **${treatmentWithOtherCritical.length}**.`);
lines.push('### Healing by target');
lines.push('| Target | Events | Requested | Actual | Overheal |');lines.push('|---|---:|---:|---:|---:|');
for(const [target,stats] of Object.entries(healingStats))lines.push(`| ${target} | ${stats.events} | ${stats.requested} | ${stats.healed} | ${stats.overheal} |`);
lines.push('');
lines.push('### Self-treatment HP distribution');
lines.push('| HP band at action | Actions |');lines.push('|---|---:|');
for(const [band,n] of Object.entries(selfHealHPBuckets))lines.push(`| ${band}% | ${n} |`);
lines.push('');
lines.push('## Damage sources into Serpent');
lines.push('| Phantom source | Total attributed damage | HP damage | Shield absorption |');lines.push('|---|---:|---:|---:|');
for(const [id,stats] of Object.entries(summary.phantomDamageIntoSerpent))lines.push(`| ${id} | ${stats.total} | ${stats.hpDamage} | ${stats.shieldDamage} |`);
lines.push('');
lines.push('## Interpretation and limitations');
lines.push('- The repeated KO pattern (Kane, Verra, Claude KO in all battles) is a high-confidence signal within this test set; it does not establish that any one skill or stat causes the losses.');
lines.push('- Phantom targeting favors Galloz and Verra. Target-decision counts include target-bearing skill decisions and may not represent only direct attacks or actual damage events.');
lines.push('- Verra often self-targets healing; this should not be called neglect without evaluating self-HP, target eligibility, MP/cooldowns, skill effects, and decision priorities.');
lines.push('- Critical-ally threshold used here is HP ≤ 30%. The decision audit is a snapshot of currently active allies; reserve bench states are excluded from this threshold analysis.');
lines.push('- These 80 battles are a forensic sample, not a balance verdict. The previous 20-pair summary is consistent with this rerun: **4 wins in 40 battles (10%)**, not 16 wins.');
fs.writeFileSync(output,lines.join('\n')+'\n');
fs.writeFileSync(output.replace(/\.md$/i,'.summary.json'),JSON.stringify(summary,null,2)+'\n');
console.log(JSON.stringify({summary,reportPath:output,jsonPath:output.replace(/\.md$/i,'.summary.json')},null,2));
